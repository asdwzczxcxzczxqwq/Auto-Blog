  '비전 시스템': ['vision', 'ocr', 'rejector', 'deep-learning', 'bcr'],
  '소프트웨어': ['mes', 'oee', 'interlock', 'pdm', 'traceability'],
  '라벨 생산': ['void', 'synthetic-label', '2d-code', 'gs1'],
  '기타 설비': ['plasma', 'porous', 'encoder'],
  '솔루션': ['gs1', 'gtin', 'gs1-128', 'bcr', 'udi'],
