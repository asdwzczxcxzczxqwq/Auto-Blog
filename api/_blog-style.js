const DEFAULT_TERM_IDS = ['cij', 'tij', 'tto', 'laser', 'vision', 'ocr'];

// 글감 텍스트와 관련된 용어만 골라 프롬프트에 넣음 (부족하면 아이템 그룹의 기본 용어로 채움)
export function selectTerms(text, group, max = 12) {
  const hits = GLOSSARY.filter((g) => g.aliases.some((a) => aliasMatches(text || '', a)));
  const fill = GROUP_TERM_IDS[group] || (hits.length < 3 ? DEFAULT_TERM_IDS : []);
  for (const id of fill) {
    if (hits.length >= 8) break;
    const g = GLOSSARY.find((x) => x.id === id);
    if (g && !hits.includes(g)) hits.push(g);
  }
  return hits.slice(0, max);
}

